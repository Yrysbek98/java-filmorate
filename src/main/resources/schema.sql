CREATE TABLE IF NOT EXISTS USERS (
   USER_ID INT PRIMARY KEY AUTO_INCREMENT,
   EMAIL VARCHAR(255) NOT NULL,
   LOGIN VARCHAR(255) NOT NULL,
   NAME VARCHAR(255),
   BIRTHDAY DATE
);

CREATE TABLE IF NOT EXISTS FRIENDS (
   USER_ID INT,
   FRIEND_ID INT,
   PRIMARY KEY (USER_ID, FRIEND_ID),
   CONSTRAINT fk_user FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
   CONSTRAINT fk_friend FOREIGN KEY (FRIEND_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS MPA (
    MPA_ID INT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS FILMS (
   FILM_ID INT PRIMARY KEY AUTO_INCREMENT,
   NAME VARCHAR(255) NOT NULL,
   DESCRIPTION TEXT,
   RELEASE_DATE DATE,
   DURATION INTEGER,
   MPA_ID INTEGER,
   CONSTRAINT fk_mpa FOREIGN KEY (MPA_ID) REFERENCES MPA(MPA_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS GENRES (
    GENRE_ID INT PRIMARY KEY AUTO_INCREMENT,
    GENRE_NAME VARCHAR(255) NOT NULL
);

-- Таблица режиссеров
CREATE TABLE IF NOT EXISTS directors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

-- Связь фильмов и режиссеров
CREATE TABLE IF NOT EXISTS film_director (
    film_id INTEGER NOT NULL REFERENCES FILMS(FILM_ID) ON DELETE CASCADE,
    director_id INTEGER NOT NULL REFERENCES directors(id) ON DELETE CASCADE,
    PRIMARY KEY (film_id, director_id)
);

CREATE TABLE IF NOT EXISTS FILM_GENRES (
    FILM_ID INT,
    GENRE_ID INT,
    PRIMARY KEY (FILM_ID, GENRE_ID),
    CONSTRAINT fk_film FOREIGN KEY (FILM_ID) REFERENCES FILMS(FILM_ID) ON DELETE CASCADE,
    CONSTRAINT fk_genre FOREIGN KEY (GENRE_ID) REFERENCES GENRES(GENRE_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS LIKES (
    FILM_ID INT,
    USER_ID INT,
    PRIMARY KEY (FILM_ID, USER_ID),
    CONSTRAINT l_film_id FOREIGN KEY (FILM_ID) REFERENCES FILMS(FILM_ID) ON DELETE CASCADE,
    CONSTRAINT l_user_id FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS REVIEWS (
    REVIEW_ID INT PRIMARY KEY AUTO_INCREMENT,
    CONTENT VARCHAR(255) NOT NULL,
    IS_POSITIVE BOOLEAN NOT NULL,
    USEFUL INT  DEFAULT 0,
    USER_ID   INT NOT NULL,
    FILM_ID  INT NOT NULL,
    CONSTRAINT unique_user_film_review UNIQUE (USER_ID, FILM_ID)
);

CREATE TABLE IF NOT EXISTS REVIEW_LIKES (
    REVIEW_ID INT,
    USER_ID INT,
    IS_LIKE BOOLEAN NOT NULL,
    PRIMARY KEY (REVIEW_ID, USER_ID),
    CONSTRAINT rl_review_id FOREIGN KEY (REVIEW_ID) REFERENCES REVIEWS(REVIEW_ID) ON DELETE CASCADE,
    CONSTRAINT rl_user_id FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS EVENTS (
    EVENT_ID INT PRIMARY KEY AUTO_INCREMENT,
    TIMESTAMP BIGINT NOT NULL,
    USER_ID INT NOT NULL,
    EVENT_TYPE VARCHAR(20) NOT NULL,
    OPERATION VARCHAR(20) NOT NULL,
    ENTITY_ID INT NOT NULL,
    CONSTRAINT e_user_id FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

